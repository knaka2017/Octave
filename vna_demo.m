%% vna_analysis 関数のデモスクリプト
% vna_analysis.m と同じディレクトリに置いて実行してください

clear all; close all; clc;

%% ============================================================
%  パラメータ設定
%% ============================================================
fs_x = 100e6;   % AWG サンプリング周波数 [Hz]
fs_z = 200e6;   % オシロ サンプリング周波数 [Hz]
N    = 1024;    % 入力信号の長さ [サンプル]

%% ============================================================
%  入力信号 x の生成（マルチサイン）
%% ============================================================
t_x    = (0:N-1)' / fs_x;
freqs_in = [1e6, 5e6, 10e6, 20e6, 30e6, 40e6];
x = zeros(N, 1);
for f = freqs_in
  x = x + sin(2*pi*f*t_x);
end
x = x / max(abs(x));

%% ============================================================
%  デモ用 DUT: 2次バンドパスフィルタを通して z を生成
%% ============================================================
f0 = 15e6; Q = 3; w0 = 2*pi*f0;
[b_d, a_d] = bilinear([w0/Q, 0], [1, w0/Q, w0^2], fs_z);

[p, q]      = rat(fs_z/fs_x, 1e-6);
x_resampled = resample(x, p, q);
N_ref       = length(x_resampled);
num_periods = 8;
M           = N_ref * num_periods;

x_rep  = repmat(x_resampled, num_periods+2, 1);
z_long = filter(b_d, a_d, x_rep);
z      = z_long(N_ref+1 : N_ref+M);

% ノイズ付加（SNR = 40 dB）
z = z + sqrt(10^(-40/10) * mean(z.^2)) * randn(size(z));

%% ============================================================
%  vna_analysis 関数の呼び出し例
%% ============================================================

% --- 例1: デフォルト（最大周期数で平均化、グラフ表示あり）---
fprintf('=== 例1: デフォルト設定 ===\n');
[freq, H] = vna_analysis(x, fs_x, z, fs_z);

% --- 例2: 平均化周期数を4に制限、周波数範囲を指定 ---
fprintf('\n=== 例2: n_avg=4, 表示範囲 0-50 MHz ===\n');
[freq2, H2] = vna_analysis(x, fs_x, z, fs_z, ...
                            'n_avg', 4, ...
                            'freq_range', [0, 50e6]);

% --- 例3: グラフ非表示、戻り値のみ取得 ---
fprintf('\n=== 例3: グラフなし（戻り値のみ） ===\n');
[freq3, H3] = vna_analysis(x, fs_x, z, fs_z, 'plot', false);

%% ============================================================
%  戻り値の使い方
%% ============================================================
fprintf('\n--- 周波数応答の取得例 ---\n');
fprintf('周波数 [MHz]  |  振幅 [dB]  |  位相 [deg]\n');
fprintf('--------------------------------------------------\n');
for f = freqs_in
  [~, idx] = min(abs(freq3 - f));
  if ~isnan(H3(idx))
    fprintf('  %8.1f   |  %7.2f    |  %8.2f\n', ...
            f/1e6, 20*log10(abs(H3(idx))), angle(H3(idx))*180/pi);
  end
end
