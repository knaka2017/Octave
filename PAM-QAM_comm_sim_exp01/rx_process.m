function rx = rx_process(cfg, tx, rxFrame, OvRx)

  rxFrame = rxFrame(:);

  % ------------------------------------------------------------
  % Matched filter corresponding to Tx pulse shape
  % Use the same pulse shape as Tx, sampled at OvRx.
  % The matched filter is time-reversed conjugate of the pulse.
  % ------------------------------------------------------------
  [pulseRx, pulseGroupDelayRx] = generate_pulse_shape(cfg, OvRx);
  mf = flipud(conj(pulseRx(:)));

  % Matched filtering
  yMF = filter(mf, 1, rxFrame);

  % ------------------------------------------------------------
  % Symbol sampling timing
  %
  % Because Tx pulse shaping is generated by conv(...,'same'),
  % and Rx uses matched filtering, there can be residual timing
  % offsets depending on pulse shape and channel.
  %
  % Here, a practical default is:
  %   sampleOffset = pulseGroupDelayRx + 1
  %
  % If needed later, this can be extended by an additional
  % cfg.symbolSampleOffset parameter or phase search.
  % ------------------------------------------------------------
  sampleOffset = pulseGroupDelayRx + 1;

  if sampleOffset < 1 || sampleOffset > length(yMF)
    error('sampleOffset is out of range.');
  end

  rawSymbols = yMF(sampleOffset:OvRx:end);

  % ------------------------------------------------------------
  % Align available symbol length with Tx symbol length
  % ------------------------------------------------------------
  nSymAvail = min(length(tx.symbols), length(rawSymbols));
  txSymbols = tx.symbols(1:nSymAvail);
  txSymIdx  = tx.symIdx(1:nSymAvail);
  rawSymbols = rawSymbols(1:nSymAvail);

  % ------------------------------------------------------------
  % Compensate Tx waveform normalization
  % Tx waveform was normalized at waveform level, but
  % symbol-domain plots / demod / EVM should stay on ideal scale.
  % ------------------------------------------------------------
  rawSymbols = rawSymbols * tx.waveScale;

  % ------------------------------------------------------------
  % Equalizer
  % ------------------------------------------------------------
  if cfg.enableEqualizer
    [eqSymbols0, w, txSymbolsEq, txSymIdxEq] = equalizer_ls( ...
      rawSymbols, txSymbols, txSymIdx, cfg.eqLen, cfg.eqDelay, cfg.eqReg);
  else
    eqSymbols0 = rawSymbols;
    w = 1;
    txSymbolsEq = txSymbols;
    txSymIdxEq = txSymIdx;
  end

  % ------------------------------------------------------------
  % Affine correction on symbol layer
  % Map equalized Rx symbols to ideal constellation scale:
  %   txSymbolsEq ≈ a * eqSymbols0 + b
  % ------------------------------------------------------------
  [eqSymbols, affineA, affineB] = affine_symbol_fit(eqSymbols0, txSymbolsEq, cfg.modType);

  % ------------------------------------------------------------
  % Demodulation using ideal constellation scale
  % ------------------------------------------------------------
  switch lower(cfg.modType)
    case 'qam'
      decSymIdx = qamdemod(eqSymbols, cfg.M);

    case 'pam'
      decSymIdx = pamdemod(real(eqSymbols), cfg.M);

    otherwise
      error('Unsupported modType: %s', cfg.modType);
  end

  decSymbols = remodulate_symbols(decSymIdx, cfg.modType, cfg.M);

  % ------------------------------------------------------------
  % Skip initial symbols for evaluation / plotting
  % ------------------------------------------------------------
  nSkip = 0;
  if isfield(cfg, 'skipInitialSymbols')
    nSkip = max(0, round(cfg.skipInitialSymbols));
  end

  nTotal = length(txSymbolsEq);
  if nTotal < 1
    error('No symbol available after matched filtering.');
  end

  if nSkip >= nTotal
    error('skipInitialSymbols is too large for available symbol length.');
  end

  keepIdx = (nSkip + 1) : nTotal;

  % ------------------------------------------------------------
  % Output
  % ------------------------------------------------------------
  rx = struct();

  % waveform-domain / full symbol-domain sequences
  rx.rxFrame = rxFrame;
  rx.mfOutput = yMF;
  rx.rawSymbols = rawSymbols;
  rx.eqWeights = w;
  rx.eqSymbolsBeforeAffine = eqSymbols0;
  rx.eqSymbolsAll = eqSymbols;
  rx.txSymbolsAlignedAll = txSymbolsEq;
  rx.txSymIdxAlignedAll = txSymIdxEq;
  rx.decSymIdxAll = decSymIdx(:);
  rx.decSymbolsAll = decSymbols(:);

  % matched filter information
  rx.pulseRx = pulseRx;
  rx.pulseGroupDelayRx = pulseGroupDelayRx;
  rx.sampleOffset = sampleOffset;
  rx.matchedFilter = mf;

  % affine correction information
  rx.affineA = affineA;
  rx.affineB = affineB;

  % skip information
  rx.skipInitialSymbols = nSkip;

  % evaluation / plotting sequences after skipping initial symbols
  rx.eqSymbols = eqSymbols(keepIdx);
  rx.txSymbolsAligned = txSymbolsEq(keepIdx);
  rx.txSymIdxAligned = txSymIdxEq(keepIdx);
  rx.decSymIdx = decSymIdx(keepIdx);
  rx.decSymbols = decSymbols(keepIdx);

end

